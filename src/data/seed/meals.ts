import { getPlaceholderImage } from '@/lib/placeholderImage'
import type { Allergen, DietaryRequirement, Ingredient, Macros, Meal, MealType, ProductCategory } from '@/types'

let counter = 0
function nextId(prefix: string): string {
  counter += 1
  return `${prefix}-${counter}`
}

function ing(
  name: string,
  quantity: number,
  unit: string,
  category: ProductCategory,
  allergens: Allergen[] = [],
): Ingredient {
  return { name, quantity, unit, category, allergens }
}

interface MealInput {
  name: string
  description: string
  type: MealType
  macros: Macros
  prepTimeMinutes: number
  cookTimeMinutes: number
  tags: string[]
  dietaryRequirements: DietaryRequirement[]
  ingredients: Ingredient[]
  method: string[]
  servings?: number
}

function buildMeal(input: MealInput): Meal {
  const allergens = Array.from(
    new Set(input.ingredients.flatMap((i) => i.allergens ?? [])),
  ) as Allergen[]
  return {
    id: nextId('meal'),
    name: input.name,
    description: input.description,
    type: input.type,
    imageUrl: getPlaceholderImage(input.name, 640),
    macros: input.macros,
    prepTimeMinutes: input.prepTimeMinutes,
    tags: input.tags,
    dietaryRequirements: input.dietaryRequirements,
    allergens,
    recipe: {
      id: nextId('recipe'),
      method: input.method,
      servings: input.servings ?? 1,
      prepTimeMinutes: input.prepTimeMinutes,
      cookTimeMinutes: input.cookTimeMinutes,
      ingredients: input.ingredients,
    },
  }
}

const M = {
  calories: (c: number, p: number, carbs: number, f: number): Macros => ({
    calories: c,
    protein: p,
    carbs,
    fat: f,
  }),
}

